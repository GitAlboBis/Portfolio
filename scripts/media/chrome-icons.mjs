// scripts/media/chrome-icons.mjs · the favicon set of the rivista (S2 chrome lane, 2026-10-09)
//
//   python scripts/media/icon-glyph.py      (writes public/proto/rivista/icons/icon.svg, the master)
//   node scripts/media/chrome-icons.mjs     (renders the PNG set from it, headless Chrome through scripts/lib/headless.mjs launch())
//
// Every PNG is the SVG master drawn by Chrome on the night ground (spec 50): the initials AT, warm white on night.
// Redrawn 2026-11-10 (integrate lane); the share of the square below is the letters' height.
//   icon-32.png              the PNG favicon for browsers without SVG favicons (A at 70 % of the square)
//   icon-192.png             the manifest's "any" icon (A at 70 %)
//   apple-touch-icon.png     180 px, the home-screen icon iOS rounds itself (A at 60 %, more paper around it)
//   icon-512-maskable.png    512 px, the manifest's maskable icon: the A sits inside the 80 % safe circle (A at 50 %)
// Provenance: the origin sentence is embedded in each PNG (tEXt) with impeccable embed-prompt.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { launch } from "../lib/headless.mjs";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "..");
const DIR = path.join(ROOT, "public", "proto", "rivista", "icons");
const svg = fs.readFileSync(path.join(DIR, "icon.svg"), "utf8");
const SET = [
  { file: "icon-32.png", size: 32, scale: 1 },
  { file: "icon-192.png", size: 192, scale: 1 },
  { file: "apple-touch-icon.png", size: 180, scale: 0.6 / 0.7 },
  { file: "icon-512-maskable.png", size: 512, scale: 0.5 / 0.7 },
];
const IMP = path.join(process.env.USERPROFILE || "C:/Users/alber", ".claude", "skills", "impeccable", "scripts", process.platform === "win32" ? "impeccable.cmd" : "impeccable");

const browser = await launch();
try {
  for (const it of SET) {
    const ctx = await browser.newContext({ viewport: { width: it.size, height: it.size }, deviceScaleFactor: 1, colorScheme: "dark" });
    const page = await ctx.newPage();
    const inner = svg.replace(/<!--[\s\S]*?-->\n?/, "");
    await page.setContent(`<!doctype html><html><head><style>html,body{margin:0;width:${it.size}px;height:${it.size}px;background:#0c0e14;overflow:hidden}
      .s{width:${it.size}px;height:${it.size}px;transform:scale(${it.scale});transform-origin:50% 50%}.s svg{display:block;width:100%;height:100%}</style></head>
      <body><div class="s">${inner}</div></body></html>`);
    const out = path.join(DIR, it.file);
    await page.screenshot({ path: out, clip: { x: 0, y: 0, width: it.size, height: it.size }, omitBackground: false });
    await ctx.close();
    const origin = `Alberto Tuveri's favicon set: ${it.file}, ${it.size}x${it.size} px, the initials AT in Sofia Sans Extra Condensed 800 (SIL OFL 1.1), warm white #f4f1ea on the night ground #0c0e14, rendered by headless Chrome (Playwright) from public/proto/rivista/icons/icon.svg, whose outline scripts/media/icon-glyph.py read with fontTools from the Google Fonts file the pages load. Rendered by scripts/media/chrome-icons.mjs on ${new Date().toISOString().slice(0, 10)}. Not generated by an image model.`;
    const pf = out + ".origin.txt";
    fs.writeFileSync(pf, origin);
    try { execFileSync(IMP, ["embed-prompt", out, "--prompt-file", pf], { stdio: "pipe", shell: process.platform === "win32" }); }
    catch (e) { console.warn(it.file + ": embed-prompt failed: " + (e.stderr ? e.stderr.toString() : e.message)); }
    fs.unlinkSync(pf);
    console.log(`${it.file}: ${it.size}px, ${fs.statSync(out).size} B`);
  }
} finally {
  await browser.close();
}
