const head = (lang) => `<!doctype html><html${lang === "en" ? "" : ` lang="${lang}"`}><head><meta charset="utf-8"><base href="${BASE}"><link rel="stylesheet" href="css/fonts.css"><style>${CSS}</style></head>`;

function card({ eyebrow, titleLines, body, fig, lang = "en" }) {
  const figure = fig.kind === "img"
    ? `<img src="${esc(fig.src)}" alt="" style="object-position:${esc(fig.pos || "50% 50%")}">`
    // (wave 8, INTEGRATE) the line in balanced rows: no word left alone on the second («… HELD IN THE / DATABASE»); set
    // on the element, so only the eight words cards change (the shared CSS is in every card's input hash)
    : `<div class="words"><p class="pf">${esc(fig.figure)}</p><p class="pl" style="text-wrap:balance">${esc(fig.line)}</p></div>`;
  return `${head(lang)}
<body><div class="card">
  <div class="col">
    ${eyebrow ? `<p class="lab">${esc(eyebrow)}</p>` : ""}
    <h1>${titleLines.map((l) => "<span>" + esc(l) + "</span>").join("")}</h1>
    ${body ? `<p class="body">${esc(body)}</p>` : ""}
    <p class="sig">Alberto Tuveri</p>
  </div>
  <div class="fig">${figure}</div>
</div></body></html>`;
}

/* the edition a card belongs to, said in its provenance sentence */
const edition = (lang) => (lang === "en" ? "" : ", " + LANGS[lang].name + " edition");
function caseCard(c, lang = "en") {
  const t = (v) => tx(v, lang);
  let fig = c.fig;
  let kind = fig.kind;
  /* a capture on hold (fig.hold, a publish gate) is the key words here too, as on the page */
  if (kind === "capture" && (fig.hold || !hasCap(fig.stem))) { fig = Object.assign({ kind: "plate" }, fig.plate); kind = "plate"; }
  const f = kind === "capture"
    ? { kind: "img", src: "/captures/" + fig.stem + "-1600.webp", pos: fig.pos, origin: "its capture public/captures/" + fig.stem + "-1600.webp (provenance in public/captures/PROVENANCE.md and the file's sidecar)" }
    : { kind: "plate", figure: t(fig.figure), line: noFolio(t(fig.figLine)), origin: "its key words, set in the display face as the Work page etches them (figure and line from parts/cases.json)" };
  return {
    file: LANGS[lang].dir + "og-" + c.slug + ".jpg",
    img: kind === "capture" ? path.join(CAPS, fig.stem + "-1600.webp") : null,
    html: card({ eyebrow: t(c.rail.kicker), titleLines: c.titleLines.map((l) => t(l)), body: t(c.rail.body), fig: f, lang }),
    what: `the share card of the case "${c.titleLines.map((l) => t(l)).join(" ")}"${edition(lang)}: its label, title and summary from parts/cases.json, set in Sofia Sans on the night ground, beside ${f.origin}`,
    plate: kind !== "capture",
  };
}
/* the cover's card: a card is a still, so it shows the cover as it prints without the stage: the name across the
   card, the role and the sentence, the signature. Its words are the hero's own entries of parts/strings.mjs */
function homeCard(lang = "en") {
  const s = (id) => tx(STR[id], lang);
  const html = `${head(lang)}
<body><div class="card cover">
  <div class="col">
    <p class="lock" data-fit="1080">Alberto Tuveri</p>
    <div class="foot">
      <div class="said"><p class="lab">${esc(s("meta.home.role"))}</p><p>${esc(s("hero.h1").replace(/<[^>]+>/g, ""))}</p></div>
    </div>
  </div>
</div></body></html>`;
  return {
    file: LANGS[lang].dir + "og-home.jpg",
    html,
    img: null,
    what: `the cover's share card${edition(lang)}: the name across the card, the role and the hero sentence of index.html, set in Sofia Sans on the night ground, as the cover prints without its live stage`,
  };
}

/** every card's job, both editions: { file, html, what, img }; file is og-<name>.jpg or it/og-<name>.jpg. A work that is
    a page of the site already ("page" in cases.json: Obla, wave 7) has no case page, so no card of its own: its page
    shares the cover's card, as every page does */
export function ogJobs() { return Object.keys(LANGS).flatMap((lang) => [homeCard(lang), ...CASES.filter((c) => !c.page).map((c) => caseCard(c, lang))]); }

/** the inputs of a card, hashed: its HTML (every word, the figure, the CSS; not the server it was drawn from) and the
    bytes of its picture */
export function ogHash(job) {
  const h = createHash("sha256").update(job.html.split(BASE).join(""));
  if (job.img && fs.existsSync(job.img)) h.update(fs.readFileSync(job.img));
  return h.digest("hex").slice(0, 16);
}
