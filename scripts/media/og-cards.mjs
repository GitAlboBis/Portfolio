// scripts/media/og-cards.mjs · the share cards of the rivista (S2 chrome lane, 2026-10-09)
//
//   node scripts/media/og-cards.mjs [name ...]      (a static server serving public/: RV_BASE, default 5178)
//   Redrawn in the night studio of spec 50 on 2026-11-10 (integrate lane): og-card-jobs.mjs holds the design.
//   names: home, <slug> for the English cards; it/home, it/<slug> for the Italian ones; it/ for all the Italian ones
//
// One 1200x630 JPEG per page and per language in public/proto/rivista/og/ (the Italian edition's in og/it/). The cards' inputs (every word, figure and picture) are built
// by og-card-jobs.mjs, pure; this script draws them in headless Chrome (scripts/lib/headless.mjs launch(), never a window) at DPR 2,
// reduces them with sharp, embeds their origin with impeccable embed-prompt, and records each card's input hash in
// og/og-manifest.json, which assemble.mjs --check compares (S2 fix, a11y review M1: three cards were stale after their
// captures and strings changed). Nothing here is generated by an image model.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import sharp from "sharp";
import { launch } from "../lib/headless.mjs";
import { OUT, ogJobs, ogHash, MANIFEST } from "./og-card-jobs.mjs";

const IMP = path.join(process.env.USERPROFILE || "C:/Users/alber", ".claude", "skills", "impeccable", "scripts", process.platform === "win32" ? "impeccable.cmd" : "impeccable");
fs.mkdirSync(OUT, { recursive: true });
const manifest = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : {};

/* S2 fix (a11y review S7): a card prints the same words and figures as its page (og-card-jobs reads cases.json and the
   pages' own meta), so the claims gate runs before a card is drawn: no card is written from a tree the gate refuses */
try {
  execFileSync(process.execPath, [fileURLToPath(new URL("../check-claims-proto.mjs", import.meta.url))], { stdio: "pipe" });
} catch (e) {
  process.stderr.write(String(e.stdout || "") + String(e.stderr || ""));
  console.error("og-cards: check-claims-proto fails on this tree; no card drawn. Fix the claim, rebuild, then rerun.");
  process.exit(1);
}

/* IT edition: a card is named as assemble.mjs --check names it: "home", "sersan-io" (English), "it/home",
   "it/sersan-io" (Italian); "it/" alone draws every Italian card. A bare name never matches the other edition's card */
const want = process.argv.slice(2);
const idOf = (file) => file.replace(/og-|\.jpg$/g, "");
const jobs = ogJobs().filter((j) => !want.length || want.some((w) => idOf(j.file) === w || (w.endsWith("/") && j.file.startsWith(w)) || (!w.includes("/") && !j.file.includes("/") && j.file.includes(w))));
const browser = await launch();
try {
  for (const j of jobs) {
    const ctx = await browser.newContext({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 2, colorScheme: "dark" });
    const page = await ctx.newPage();
    const errs = [];
    page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
    page.on("requestfailed", (r) => errs.push("failed " + r.url()));
    await page.setContent(j.html, { waitUntil: "load" });
    await page.evaluate(async () => {
      /* the night studio's one superfamily (spec 50 §2), from css/fonts.css */
      await Promise.all(['800 1em "Sofia Sans Extra Condensed"', '400 1em "Sofia Sans"', '500 1em "Sofia Sans"', '600 1em "Sofia Sans Condensed"'].map((f) => document.fonts.load(f)));
      await document.fonts.ready;
      /* fit: the title (or the name) and the key words shrink until they hold their measure */
      const fit = (el, prop, max, min, width) => {
        if (!el) return;
        let s = max;
        el.style.setProperty(prop, s + "px");
        const w = () => Math.max(...Array.from(el.children.length ? el.children : [el]).map((c) => c.scrollWidth));
        while (s > min && w() > width) { s -= 2; el.style.setProperty(prop, s + "px"); }
      };
      fit(document.querySelector("h1"), "--fs", 104, 40, 520);
      { const lock = document.querySelector(".lock"); fit(lock, "--fs", 260, 60, lock && lock.dataset.fit ? +lock.dataset.fit : 1080); }
      const pf = document.querySelector(".words .pf");
      if (pf) fit(pf, "--pf", 230, 60, 448);
      /* the column never runs into the signature: the summary line goes first */
      const col = document.querySelector(".col"), body = document.querySelector(".col .body"), sig = document.querySelector(".sig");
      if (col && body && sig && body.getBoundingClientRect().bottom > sig.getBoundingClientRect().top - 24) body.remove();
      await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
    });
    const png = await page.screenshot({ type: "png" });
    await ctx.close();
    if (errs.length) console.warn(j.file + ": " + errs.join(" | "));
    const out = path.join(OUT, j.file);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const buf = await sharp(png).resize(1200, 630, { kernel: "lanczos3" }).jpeg({ quality: 86, mozjpeg: true, chromaSubsampling: "4:4:4" }).toBuffer();
    fs.writeFileSync(out, buf);
    const origin = `Alberto Tuveri's share card ${j.file}, 1200x630: ${j.what}. Drawn by headless Chrome (Playwright, DPR 2) from an HTML card in the site's own design system and reduced with sharp ${sharp.versions.sharp}; written by scripts/media/og-cards.mjs on ${new Date().toISOString().slice(0, 10)}. Not generated by an image model.`;
    const pf = out + ".origin.txt";
    fs.writeFileSync(pf, origin);
    try { execFileSync(IMP, ["embed-prompt", out, "--prompt-file", pf], { stdio: "pipe", shell: process.platform === "win32" }); }
    catch (e) { console.warn(j.file + ": embed-prompt failed: " + (e.stderr ? e.stderr.toString() : e.message)); }
    fs.unlinkSync(pf);
    manifest[j.file] = ogHash(j);
    console.log(`${j.file}: ${(fs.statSync(out).size / 1024).toFixed(1)} KB`);
  }
} finally {
  await browser.close();
  fs.writeFileSync(MANIFEST, JSON.stringify(Object.fromEntries(Object.keys(manifest).sort().map((k) => [k, manifest[k]])), null, 2) + "\n");
}
